<?php

// Usage: php script/sync-mk-schema.php [--apply]
// Only mk_ tables may be changed. Reference SQL is parsed, never executed wholesale.
require dirname(__DIR__).'/vendor/autoload.php';
$app = require dirname(__DIR__).'/bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();
$db = Illuminate\Support\Facades\DB::connection();
$quote = fn ($s) => '"'.str_replace('"', '""', $s).'"';
$references = json_decode(ltrim(file_get_contents(__DIR__.'/mk-reference.json'), "\xEF\xBB\xBF"), true, 512, JSON_THROW_ON_ERROR);
$plan = [];
$differences = [];
$add = function ($table, $sql, $kind) use (&$plan) {
    if (! str_starts_with($table, 'mk_')) {
        throw new RuntimeException('Refusing to modify non-mk_ table');
    }
    $plan[] = compact('table', 'sql', 'kind');
};
$normalize = fn ($s) => preg_replace('/\s+/', ' ', strtolower(str_replace(['"', 'public.'], '', trim($s))));
$constraints = [];
$allTables = array_column($db->select("SELECT tablename FROM pg_tables WHERE schemaname='public' AND left(tablename,3)='mk_'"), 'tablename');
$allColumns = $db->select("SELECT t.relname AS table_name, a.attname AS name, format_type(a.atttypid,a.atttypmod) AS type, a.attnotnull AS not_null, pg_get_expr(d.adbin,d.adrelid) AS default_value FROM pg_class t JOIN pg_namespace n ON n.oid=t.relnamespace JOIN pg_attribute a ON a.attrelid=t.oid LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum WHERE n.nspname='public' AND left(t.relname,3)='mk_' AND a.attnum>0 AND NOT a.attisdropped");
$allConstraints = $db->select("SELECT t.relname AS table_name, c.conname AS name, pg_get_constraintdef(c.oid) AS definition FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace n ON n.oid=t.relnamespace WHERE n.nspname='public' AND left(t.relname,3)='mk_'");
foreach ($references as $reference) {
    $table = $reference['table'];
    $exists = in_array($table, $allTables, true);
    $columns = array_filter($allColumns, fn ($column) => $column->table_name === $table);
    $columns = array_column($columns, null, 'name');
    $existingConstraints = array_filter($allConstraints, fn ($constraint) => $constraint->table_name === $table);
    $definitions = [];
    $lines = preg_split('/\r?\n/', trim($reference['body']));
    foreach ($lines as $line) {
        $line = rtrim(trim($line), ',');
        if (preg_match('/^CONSTRAINT (\w+) (.+)$/', $line, $match)) {
            $constraints[] = [$table, $match[1], $match[2], $existingConstraints];
            continue;
        }
        if (! preg_match('/^(\w+) (.+)$/', $line, $match)) {
            throw new RuntimeException('Unrecognized schema line: '.$line);
        }
        [$unused, $column, $definition] = $match;
        if (preg_match('/\bUNIQUE\b/', $definition)) {
            $constraints[] = [$table, $table.'_'.$column.'_key', 'UNIQUE ('.$quote($column).')', $existingConstraints];
            $definition = preg_replace('/\s+UNIQUE\b/', '', $definition);
        }
        // An identity column avoids relying on sequences missing from the context export.
        $definition = preg_replace("/DEFAULT nextval\('[^']+'::regclass\)/", 'GENERATED BY DEFAULT AS IDENTITY', $definition);
        $definitions[] = $quote($column).' '.$definition;
        if ($exists && ! isset($columns[$column])) {
            $add($table, 'ALTER TABLE public.'.$quote($table).' ADD COLUMN '.$quote($column).' '.$definition, 'column');
        } elseif (isset($columns[$column])) {
            $expectedType = preg_split('/\s+(?:NOT NULL|DEFAULT|GENERATED|CHECK)\b/', $definition)[0];
            if ($normalize($expectedType) !== $normalize($columns[$column]->type)) {
                $differences[] = ['table'=>$table, 'column'=>$column, 'type_current'=>$columns[$column]->type, 'type_reference'=>$expectedType];
                $safeWidening = preg_match('/^(character varying|numeric|timestamp|time)\(\d+(?:,\d+)?\)/', $columns[$column]->type)
                    && preg_replace('/\(\d+(?:,\d+)?\)/', '', $columns[$column]->type) === $expectedType;
                if ($safeWidening) {
                    $add($table, 'ALTER TABLE public.'.$quote($table).' ALTER COLUMN '.$quote($column).' TYPE '.$expectedType, 'type');
                }
            }
            $expectedNotNull = str_contains($definition, 'NOT NULL');
            if ($expectedNotNull !== (bool) $columns[$column]->not_null) {
                $differences[] = ['table'=>$table, 'column'=>$column, 'nullable_current'=>!$columns[$column]->not_null, 'nullable_reference'=>!$expectedNotNull];
                $add($table, 'ALTER TABLE public.'.$quote($table).' ALTER COLUMN '.$quote($column).($expectedNotNull ? ' SET NOT NULL' : ' DROP NOT NULL'), 'nullable');
            }
            if (! str_contains($definition, 'GENERATED')) {
                preg_match('/\bDEFAULT (.*?)(?: CHECK\b.*)?$/', $definition, $defaultMatch);
                $expectedDefault = $defaultMatch[1] ?? null;
                $actualDefault = $columns[$column]->default_value;
                if ($normalize($expectedDefault ?? '') !== $normalize($actualDefault ?? '')) {
                    $differences[] = ['table'=>$table, 'column'=>$column, 'default_current'=>$actualDefault, 'default_reference'=>$expectedDefault];
                    $add($table, 'ALTER TABLE public.'.$quote($table).' ALTER COLUMN '.$quote($column).($expectedDefault === null ? ' DROP DEFAULT' : ' SET DEFAULT '.$expectedDefault), 'default');
                }
            }
        }
    }
    if (! $exists) {
        $add($table, 'CREATE TABLE public.'.$quote($table).' ('.implode(', ', $definitions).')', 'table');
    }
}
// All parent keys must exist before adding any foreign keys.
usort($constraints, fn ($a, $b) => (str_starts_with($a[2], 'FOREIGN KEY') ? 1 : 0) <=> (str_starts_with($b[2], 'FOREIGN KEY') ? 1 : 0));
foreach ($constraints as [$table, $name, $definition, $existing]) {
    $found = false;
    foreach ($existing as $constraint) {
        // Preserve existing delete/update actions supplied by application migrations.
        $signature = fn ($s) => preg_replace('/\s+(?:ON (?:DELETE|UPDATE)|DEFERRABLE|NOT VALID).*$/i', '', $normalize($s));
        if ($signature($constraint->definition) === $signature($definition)) {
            $found = true;
            break;
        }
    }
    if (! $found) {
        $add($table, 'ALTER TABLE public.'.$quote($table).' ADD CONSTRAINT '.$quote($name).' '.$definition, 'constraint');
    }
}
$report = ['reference_tables'=>count($references), 'operations'=>$plan, 'column_differences'=>$differences];
file_put_contents(__DIR__.'/mk-schema-comparison.json', json_encode($report, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
echo 'Reference tables: '.count($references).'; planned operations: '.count($plan).'; column differences: '.count($differences).PHP_EOL;
foreach ($plan as $operation) {
    echo $operation['kind'].' '.$operation['table'].': '.$operation['sql'].PHP_EOL;
}
if (! in_array('--apply', $argv, true) && ! in_array('--check', $argv, true)) {
    exit;
}
$errors = [];
$apply = in_array('--apply', $argv, true);
$skipped = [];
if (in_array('--safe', $argv, true)) {
    $knownErrors = json_decode(file_get_contents(__DIR__.'/mk-schema-validation.json'), true, 512, JSON_THROW_ON_ERROR);
    $failedSql = array_column(array_column($knownErrors, 'operation'), 'sql');
    $skipped = array_values(array_filter($plan, fn ($operation) => in_array($operation['sql'], $failedSql, true)));
    $plan = array_values(array_filter($plan, fn ($operation) => ! in_array($operation['sql'], $failedSql, true)));
    file_put_contents(__DIR__.'/mk-schema-blocked.json', json_encode($knownErrors, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
    echo 'Skipped known data conflicts: '.count($skipped).PHP_EOL;
}
file_put_contents(__DIR__.'/mk-schema-before.json', json_encode(['columns'=>$allColumns, 'constraints'=>$allConstraints], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
$db->beginTransaction();
try {
    $db->statement("SET LOCAL lock_timeout = '10s'");
    $db->statement("SET LOCAL statement_timeout = '90s'");
    foreach ($plan as $index => $operation) {
        $db->statement('SAVEPOINT mk_sync_step');
        try {
            $db->statement($operation['sql']);
        } catch (Throwable $error) {
            $db->statement('ROLLBACK TO SAVEPOINT mk_sync_step');
            $errors[] = ['operation'=>$operation, 'error'=>$error->getMessage()];
        }
        $db->statement('RELEASE SAVEPOINT mk_sync_step');
    }
    if ($errors || ! $apply) {
        $db->rollBack();
        echo 'Rolled back. Validation errors: '.count($errors).PHP_EOL;
    } else {
        $db->commit();
        echo 'Applied successfully in one transaction.'.PHP_EOL;
    }
} catch (Throwable $error) {
    $db->rollBack();
    throw $error;
}
file_put_contents(__DIR__.'/mk-schema-validation.json', json_encode($errors, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
foreach ($errors as $error) {
    echo $error['operation']['table'].': '.$error['error'].PHP_EOL;
}
exit($errors ? 1 : 0);
